"""Stage 11b (local fine-tuned model) vs the same default runs without it: macro semantics / roles / overall F1 against
the truth files, paired bootstrap CI over 14 protocols, labels applied / rejected. usage: gen_tex.py <out.tex>"""
import json, random, re, sys, glob, os
H = '/mnt/d/tez/practical/protocol_re/dol/llm-semantics-eval/runs'
P = ['bacnet', 'cip', 'dnp3', 'enip', 'ethercat', 'goose', 'hart_ip', 'iec104', 'mms', 'modbus', 'opcua', 'powerlink', 's7comm', 'zigbee']
K = {'overall': None, 'sem': 'field_semantics', 'roles': 'field_roles', 'bnd': 'field_boundary'}
def load(p, v):
    r = json.load(open(f'{H}/{p}/{v}/data/15_evaluation_result.json'))
    return {k: (r['summary']['overall_score'] if m is None else r['metrics'][m]['f1_score']) for k, m in K.items()}
base = {p: load(p, 'check') for p in P}; llm = {p: load(p, 'llm') for p in P}
applied = rejected = 0
for p in P:
    t = open(f'{H}/{p}/llm/log/11b.out').read()
    applied += int(re.search(r'Total labels applied: (\d+)', t).group(1)); rejected += int(re.search(r'Total labels rejected: (\d+)', t).group(1))
def fa(t):
    t = t.lstrip('+').replace('.', '٫')
    return r'\fanum{' + t.translate(str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹')) + '}' if '٫' in t else t
L = ['% generated by dol/llm-semantics-eval/gen_tex.py -- do not edit by hand', r'\newcommand{\LS}[2]{\csname LS:#1:#2\endcsname}', r'\newcommand{\LSF}[2]{\csname LSF:#1:#2\endcsname}']
def put(a, b, t):
    L.append(rf'\expandafter\def\csname LS:{a}:{b}\endcsname{{{t}}}'); L.append(rf'\expandafter\def\csname LSF:{a}:{b}\endcsname{{{fa(t)}}}')
out = []
for k in K:
    d = [llm[p][k] - base[p][k] for p in P]
    rng = random.Random(0); bs = sorted(sum(rng.choice(d) for _ in d) / 14 for _ in range(10000))
    m, lo, hi = sum(d) / 14, bs[250], bs[9750]; up, dn = sum(x > .005 for x in d), sum(x < -.005 for x in d)
    put(k, 'base', f'{sum(base[p][k] for p in P)/14:.3f}'); put(k, 'llm', f'{sum(llm[p][k] for p in P)/14:.3f}')
    put(k, 'd', f'{m:+.3f}'); put(k, 'lo', f'{lo:+.3f}'); put(k, 'hi', f'{hi:+.3f}'); put(k, 'up', str(up)); put(k, 'down', str(dn))
    out.append(f'{k:8s} base {sum(base[p][k] for p in P)/14:.3f} llm {sum(llm[p][k] for p in P)/14:.3f} diff {m:+.4f} [{lo:+.4f}, {hi:+.4f}] up/down {up}/{dn}')
put('labels', 'applied', str(applied)); put('labels', 'rejected', str(rejected))
for p in P:
    out.append(f'  {p:10s} ' + ' '.join(f'{k}={base[p][k]:.3f}->{llm[p][k]:.3f}' for k in K))
open(sys.argv[1], 'w').write('\n'.join(L) + '\n'); open(os.path.join(os.path.dirname(H), 'summary.txt'), 'w').write('\n'.join(out) + f'\napplied {applied} rejected {rejected}\n')
print('\n'.join(out)); print('applied', applied, 'rejected', rejected)
# role disagreements (role_disagreements.py): where 11b changed a field's role, who matches the covering truth field
dz = json.load(open(os.path.join(os.path.dirname(H), 'role_disagreements.json')))
t = dz['total']
for k in ('changed', 'judged', 'heuristic_right', 'llm_right', 'both_wrong', 'exact', 'unmatched_family', 'no_truth_role'):
    put('dis', k, str(t[k]))
d = [(c['llm_right'] - c['heuristic_right']) / c['judged'] for c in dz['per_protocol'].values() if c['judged']]
rng = random.Random(0); bs = sorted(sum(rng.choice(d) for _ in d) / len(d) for _ in range(10000))
put('dis', 'nprot', str(len(d))); put('dis', 'd', f'{sum(d)/len(d):+.3f}'); put('dis', 'lo', f'{bs[250]:+.3f}'); put('dis', 'hi', f'{bs[9750]:+.3f}')
top = sorted(dz['per_protocol'].items(), key=lambda kv: -kv[1]['llm_right'])[:2]
put('dis', 'top', str(sum(c['llm_right'] for _, c in top)))
open(sys.argv[1], 'w').write('\n'.join(L) + '\n')
