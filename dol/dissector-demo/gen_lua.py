"""Export an inferred protocol model (stage 12, 10_protocol_model.json) as a Wireshark Lua dissector.

The dissector assigns each payload as stage 04 does: among the families whose length range contains the payload
length and whose constant at the discovered global discriminator (02_family_assignments.json next to the model)
matches, the one whose other template constants (those inside the payload) match best, if at least half match; then adds every field hypothesis of that family with its
inferred width and byte order. Fields are exposed twice: per family (inferred.<family>.f<offset>) and per semantic
role (inferred.<role>, e.g. inferred.opcode, inferred.transaction_id), so display filters and IDS-style rules can be
written against the inferred model without knowing the protocol.
usage: gen_lua.py <10_protocol_model.json> <out.lua> --tcp-port N | --udp-port N"""
import argparse, json, re

ap = argparse.ArgumentParser()
ap.add_argument('model'); ap.add_argument('out')
ap.add_argument('--tcp-port', type=int); ap.add_argument('--udp-port', type=int)
a = ap.parse_args()
m = json.load(open(a.model))
import os
asg = os.path.join(os.path.dirname(a.model), '02_family_assignments.json')
ref = (json.load(open(asg)).get('metadata') or {}).get('discriminator_refinement') or {} if os.path.exists(asg) else {}
disc = list(range(int(ref['offset']), int(ref['offset']) + int(ref['width']))) if ref.get('applied') else []
fams = m['families'] if isinstance(m['families'], list) else list(m['families'].values())

def ident(s): return re.sub(r'[^a-z0-9_]', '_', str(s).lower())

roles, lines = set(), []
specs = []
for f in fams:
    if f.get('family_id') in (None, 'noise'):
        continue
    tmpl = f.get('template', '').split()
    consts = [(i, int(t, 16)) for i, t in enumerate(tmpl) if t != '??']
    ls = (f.get('feature_summary') or {}).get('length_stats') or {}
    lo, hi = int(ls.get('min', len(tmpl))), int(ls.get('max', len(tmpl)))
    fields = []
    for h in sorted(f.get('field_hypotheses') or [], key=lambda h: int(h['start'])):
        st, ln = int(h['start']), int(h.get('length') or 0)
        if ln <= 0:
            continue
        role = (h.get('attributes') or {}).get('semantic_role') or h.get('field_type') or 'field'
        ft = str(h.get('field_type') or '')
        le = ft.endswith('_le') or h.get('endian') == 'little'
        fields.append((st, ln, ident(role), le))
        if ln in (1, 2, 4):
            roles.add(ident(role))
    specs.append((ident(f['family_id']), f.get('role') or 'unknown', consts, lo, hi, fields))

L = ['-- generated by dol/dissector-demo/gen_lua.py from ' + a.model,
     'local p = Proto("inferred", "Inferred protocol (protocol_re)")',
     'local F = {}',
     'F.family = ProtoField.string("inferred.family", "Family")',
     'F.role = ProtoField.string("inferred.role", "Role")',
     'local DISC = {' + ', '.join(str(o) for o in disc) + '}']
for r in sorted(roles):
    L.append(f'F["r_{r}"] = ProtoField.uint32("inferred.{r}", "{r}")')
for fid, _, _, _, _, fields in specs:
    for st, ln, role, le in fields:
        kind = 'ProtoField.uint32' if ln in (1, 2, 4) else 'ProtoField.bytes'
        L.append(f'F["{fid}_{st}"] = {kind}("inferred.{fid}.f{st}", "{role} @{st}")')
L.append('local list = {} for _, v in pairs(F) do table.insert(list, v) end p.fields = list')
L.append('local FAM = {')
for fid, role, consts, lo, hi, fields in specs:
    c = ', '.join(f'{{{o}, {v}}}' for o, v in consts)
    fl = ', '.join(f'{{{st}, {ln}, "{r}", {str(le).lower()}}}' for st, ln, r, le in fields)
    L.append(f'  {{id = "{fid}", role = "{role}", lo = {lo}, hi = {hi}, c = {{{c}}}, f = {{{fl}}}}},')
L.append('}')
L.append('''function p.dissector(tvb, pinfo, tree)
  local n = tvb:len()
  if n == 0 then return 0 end
  local best, score = nil, 0.5
  for _, fam in ipairs(FAM) do
    if n >= fam.lo and n <= fam.hi then
      local ok, hit, tot = true, 0, 0
      for _, c in ipairs(fam.c) do
        if c[1] < n then
          local eq = tvb(c[1], 1):uint() == c[2]
          for _, d in ipairs(DISC) do if d == c[1] and not eq then ok = false end end
          tot = tot + 1
          if eq then hit = hit + 1 end
        end
      end
      local sc = tot > 0 and hit / tot or 0
      if ok and sc > score then best, score = fam, sc end
    end
  end
  pinfo.cols.protocol = "INFERRED"
  local t = tree:add(p, tvb(), "Inferred protocol")
  if not best then t:add(F.family, "unmatched") return n end
  t:add(F.family, best.id); t:add(F.role, best.role)
  pinfo.cols.info = best.id .. " (" .. best.role .. ")"
  for _, fd in ipairs(best.f) do
    local st, ln, role, le = fd[1], fd[2], fd[3], fd[4]
    if st + ln <= n then
      local r = tvb(st, ln)
      local per = F[best.id .. "_" .. st]
      if ln == 1 or ln == 2 or ln == 4 then
        local v = le and r:le_uint() or r:uint()
        t:add(per, r, v)
        if F["r_" .. role] then t:add(F["r_" .. role], r, v) end
      else
        t:add(per, r)
      end
    end
  end
  return n
end''')
if a.tcp_port:
    L.append(f'DissectorTable.get("tcp.port"):add({a.tcp_port}, p)')
if a.udp_port:
    L.append(f'DissectorTable.get("udp.port"):add({a.udp_port}, p)')
open(a.out, 'w').write('\n'.join(L) + '\n')
print(f'wrote {a.out}: {len(specs)} families, roles {sorted(roles)}')
