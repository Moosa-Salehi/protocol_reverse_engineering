"""Thesis macros for the dissector demo (sec:r-dissector): \\DD{corpus}{key}. usage: gen_tex.py <out.tex>"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
def fa(t):
    t = t.replace('.', '٫')
    return r'\fanum{' + t.translate(str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹')) + '}' if ('٫' in t or '٬' in t) else t.translate(str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹'))
L = ['% generated by dol/dissector-demo/gen_tex.py -- do not edit by hand', r'\newcommand{\DD}[2]{\csname DD:#1:#2\endcsname}']
def put(c, k, v):
    L.append(rf'\expandafter\def\csname DD:{c}:{k}\endcsname{{{fa(v)}}}')
for c in ('modbus_single', 'benchmark_modbus'):
    d = json.load(open(f'{HERE}/{c}.json'))
    put(c, 'packets', f"{d['modbus_packets']:,}".replace(',', '٬'))
    put(c, 'cov', f"{100 * d['coverage']:.1f}"); put(c, 'pur', f"{100 * d['family_purity']:.1f}"); put(c, 'fams', str(d['families']))
    for k in ('opcode', 'transaction_id', 'length'):
        put(c, k, f"{100 * d['values'][k]['equal']:.1f}")
    for v, r in d['rules'].items():
        put(c, f'j{v}', f"{r['jaccard']:.3f}")
open(sys.argv[1], 'w').write('\n'.join(L) + '\n')
