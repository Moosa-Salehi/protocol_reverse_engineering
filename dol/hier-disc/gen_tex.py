"""Family-discovery error analysis for the thesis (sec:r-family): per protocol, families vs in-scope truth types,
matched / extra families / missed types (default configuration, dol/final-v4/zs, truth-aligned evaluator); boundary
F1 with all fields vs only the fields of matched families and types (the ceiling for perfect family matching); the
second-level discriminator prototypes (hier.json: length rule, layout_select.json: layout agreement) and the full
pipeline run of the layout rule (dol/disc-split/score.json). usage: gen_tex.py <out.tex>"""
import importlib.util, json, os, sys
ROOT = '/mnt/d/tez/practical/protocol_re'; HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('ev', f'{ROOT}/scripts/17_evaluate_protocol_spec.py'); ev = importlib.util.module_from_spec(spec); spec.loader.exec_module(ev)
P = ['bacnet', 'cip', 'dnp3', 'enip', 'ethercat', 'goose', 'hart_ip', 'iec104', 'mms', 'modbus', 'opcua', 'powerlink', 's7comm', 'zigbee']
H = ['synphasor', 'ams', 'doip', 'cnip']
LABEL = {'bacnet': 'BACnet', 'cip': 'CIP', 'dnp3': 'DNP3', 'enip': 'EtherNet/IP', 'ethercat': 'EtherCAT', 'goose': 'GOOSE', 'hart_ip': 'HART-IP',
         'iec104': 'IEC 104', 'mms': 'MMS', 'modbus': 'Modbus', 'opcua': 'OPC UA', 'powerlink': 'POWERLINK', 's7comm': 'S7comm', 'zigbee': 'ZigBee'}
rows, f_all, f_m, framing_ok, fams_total = [], [], [], 0, 0
for p in P:
    d = f'{ROOT}/dol/final-v4/zs/{p}/data'; r = json.load(open(f'{d}/15_evaluation_result.json'))
    b = r['metrics']['field_boundary']; mt = r['metrics']['message_type_matching']
    mf = {x['predicted_family_id'] for x in r['matches']['message_types']}; mtp = {x['ground_truth_message_type_id'] for x in r['matches']['message_types']}
    tp = b['true_positives']
    fp_m = sum(1 for u in r['unmatched']['predicted_fields'] if u['owner_id'] in mf)
    fn_m = sum(1 for u in r['unmatched']['ground_truth_fields'] if u['owner_id'] in mtp)
    Pm = tp / max(1, tp + fp_m); Rm = tp / max(1, tp + fn_m); Fm = 2 * Pm * Rm / max(1e-9, Pm + Rm)
    fams = json.load(open(f'{d}/14_evaluation_model_data.json'))['predicted_protocol']['families']
    truth = json.load(open(f'{ROOT}/truth_files/{p}.json')); tp_ = truth.get('ground_truth_protocol') or truth.get('predicted_protocol')
    hl = ev._truth_header_length(tp_['message_types'])
    framing_ok += sum(1 for f in fams if ev._family_body_offset(f) == hl); fams_total += len(fams)
    scope = len(r['truth_scope'].get('in_scope_message_type_ids') or [])
    rows.append(f"{LABEL[p]} & {len(fams)} & {scope} & {mt['true_positives']} & {mt['false_positives']} & {mt['false_negatives']} & {b['f1_score']:.3f} & {Fm:.3f} \\\\")
    f_all.append(b['f1_score']); f_m.append(Fm)
hier = json.load(open(f'{HERE}/hier.json'))['protocols']; lay = json.load(open(f'{HERE}/layout_select.json'))
ds = json.load(open(f'{ROOT}/dol/disc-split/score.json'))
def mean(src, grp, when, k):
    ps = H if grp == 'h' else P
    return sum(src[p][when][k] for p in ps) / len(ps)
L = ['% generated by dol/hier-disc/gen_tex.py -- do not edit by hand', r'\newcommand{\FD}[1]{\csname FD:#1\endcsname}', r'\newcommand{\FDF}[1]{\csname FDF:#1\endcsname}']
def fa(t):
    t = t.replace('.', '٫'); return r'\fanum{' + t.translate(str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹')) + '}' if '٫' in t else t
def put(k, t):
    L.append(rf'\expandafter\def\csname FD:{k}\endcsname{{{t}}}'); L.append(rf'\expandafter\def\csname FDF:{k}\endcsname{{{fa(t)}}}')
put('fall', f'{sum(f_all)/14:.3f}'); put('fmatched', f'{sum(f_m)/14:.3f}'); put('framingok', str(framing_ok)); put('families', str(fams_total))
for name, src in (('len', hier), ('lay', lay)):
    for g in ('b', 'h'):
        for k in ('v', 'ari'):
            put(f'{name}{g}{k}0', f"{mean(src, g, 'before', k):.3f}"); put(f'{name}{g}{k}1', f"{mean(src, g, 'after', k):.3f}")
for k in ('overall', 'bnd'):
    put(f'ds{k}0', f"{sum(ds['bench'][p]['before'][k] for p in P)/14:.3f}"); put(f'ds{k}1', f"{sum(ds['bench'][p]['after'][k] for p in P)/14:.3f}")
put('dspm0', f"{sum(ds['heldout'][p]['before']['pm'] for p in H)/4:.3f}"); put('dspm1', f"{sum(ds['heldout'][p]['after']['pm'] for p in H)/4:.3f}")
for p in ('mms', 'ethercat'):
    put(f'ds{p}0', f"{ds['bench'][p]['before']['overall']:.3f}"); put(f'ds{p}1', f"{ds['bench'][p]['after']['overall']:.3f}")
put('amsv0', f"{hier['ams']['before']['v']:.3f}"); put('amsv1', f"{hier['ams']['after']['v']:.3f}")
put('opcuav0', f"{hier['opcua']['before']['v']:.3f}"); put('opcuav1', f"{hier['opcua']['after']['v']:.3f}")
L.append(r'\newcommand{\FamilyRows}{%'); L += rows; L.append('}')
open(sys.argv[1], 'w').write('\n'.join(L) + '\n'); print('\n'.join(rows)); print('ceiling', sum(f_all)/14, sum(f_m)/14, framing_ok, fams_total)
