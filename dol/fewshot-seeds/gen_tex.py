"""Few-shot 50 over five label selections (seed 20261017 = dol/final-v4/fs50, seeds 1-4 = runs/seed<k>): macro overall
and boundary F1 against the truth files, per-message boundary F1 on the comparison sample (truth convention, labelled
messages of that seed not scored), and the difference to zero-shot. usage: gen_tex.py <out.tex>"""
import json, os, random, sys
ROOT = '/mnt/d/tez/practical/protocol_re'; HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, f'{ROOT}/dol/baseline-comparison/scripts'); sys.path.insert(0, f'{ROOT}/src')
from common import PROTOCOLS as P, BENCH, iter_jsonl
from protocol_re.inference.tlv import message_layout_edges
RUNS = {'20261017': f'{ROOT}/dol/final-v4/fs50', **{str(k): f'{HERE}/runs/seed{k}' for k in (1, 2, 3, 4)}}
LABELS = {'20261017': f'{ROOT}/dol/accuracy-push/integrated-labels', **{str(k): f'{HERE}/labels-seed{k}' for k in (1, 2, 3, 4)}}
def res(run, p):
    r = json.load(open(f'{run}/{p}/data/15_evaluation_result.json'))
    return r['summary']['overall_score'], r['metrics']['field_boundary']['f1_score'], r['metrics']['field_semantics']['f1_score']
def pm(run, p, labelled):
    d = f'{run}/{p}/data'; fams = json.load(open(f'{d}/05_families.json'))
    assign = {a['msg_id']: str(a['family_id']) for a in json.load(open(f'{d}/02_family_assignments.json'))['assignments']}
    edges = {f: sorted({x for fl in det.get('field_hypotheses', []) or [] for x in (int(fl.get('start', 0) or 0), int(fl.get('start', 0) or 0) + int(fl.get('length', 0) or 0))}) for f, det in fams.items()}
    ids = set(json.load(open(f'{ROOT}/dol/baseline-comparison/samples/{p}.json'))) - labelled
    ref = {a['msg_id']: a['boundaries'] for a in iter_jsonl(f'{ROOT}/dol/accuracy-push/annotations-truthconv/{p}.jsonl') if a['msg_id'] in ids}
    tp = fp = fn = 0
    for r in iter_jsonl(f'{BENCH}/{p}/data/01_messages.jsonl'):
        m = r['msg_id']
        if m not in ref: continue
        L = r['payload_len']; f = assign.get(m); e = edges.get(f, [])
        lay = fams.get(f, {}).get('message_layout') if f else None
        if lay: e = message_layout_edges(bytes.fromhex(r['payload_hex']), e, lay)
        t = {x for x in ref[m] if 0 < x < L}; q = {x for x in e if 0 < x < L}
        tp += len(t & q); fp += len(q - t); fn += len(t - q)
    Pr = tp / max(1, tp + fp); R = tp / max(1, tp + fn); return 2 * Pr * R / max(1e-9, Pr + R)
zs = {p: res(f'{ROOT}/dol/final-v4/zs', p)[0] for p in P}
rows = {}
for s, run in RUNS.items():
    lab = {p: {json.loads(l)['msg_id'] for l in open(f'{LABELS[s]}/{p}.jsonl')} for p in P}
    o = [res(run, p) for p in P]
    d = [x[0] - zs[p] for x, p in zip(o, P)]
    rng = random.Random(0); bs = sorted(sum(rng.choice(d) for _ in d) / 14 for _ in range(10000))
    rows[s] = dict(overall=sum(x[0] for x in o) / 14, bnd=sum(x[1] for x in o) / 14, sem=sum(x[2] for x in o) / 14,
                   pm=sum(pm(run, p, lab[p]) for p in P) / 14, dzs=sum(d) / 14, lo=bs[250], hi=bs[9750], up=sum(x > .005 for x in d))
    print(s, {k: round(v, 3) for k, v in rows[s].items()})
def fa(t):
    t = t.replace('.', '٫'); return r'\fanum{' + t.translate(str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹')) + '}' if '٫' in t else t
L = ['% generated by dol/fewshot-seeds/gen_tex.py -- do not edit by hand', r'\newcommand{\SD}[1]{\csname SD:#1\endcsname}', r'\newcommand{\SDF}[1]{\csname SDF:#1\endcsname}']
def put(k, t):
    L.append(rf'\expandafter\def\csname SD:{k}\endcsname{{{t}}}'); L.append(rf'\expandafter\def\csname SDF:{k}\endcsname{{{fa(t)}}}')
for k in ('overall', 'bnd', 'sem', 'pm'):
    v = [r[k] for r in rows.values()]
    put(f'{k}min', f'{min(v):.3f}'); put(f'{k}max', f'{max(v):.3f}'); put(f'{k}mean', f'{sum(v)/len(v):.3f}')
put('dzsmin', f"{min(r['dzs'] for r in rows.values()):+.3f}"); put('dzsmax', f"{max(r['dzs'] for r in rows.values()):+.3f}")
put('allsig', 'yes' if all(r['lo'] > 0 for r in rows.values()) else 'no')
put('minlo', f"{min(r['lo'] for r in rows.values()):+.3f}")
open(sys.argv[1], 'w').write('\n'.join(L) + '\n'); print('all seeds significant over zero-shot:', all(r['lo'] > 0 for r in rows.values()))
