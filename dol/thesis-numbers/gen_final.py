"""Macros for the supplementary corpora and the runtime measurement (final code, default configuration, dol/thesis-final-zs).
usage: gen_final.py <out.tex>
  \\SUP{corpus}{metric} / \\SUPF (Persian decimal): corpus in modbus-single modbus-small sajjad goose;
     metric overall mt bnd sem rel families messages
  \\TIME{n}{group}: seconds per stage group (n10000 ... n200000; groups s04 s04b s05 s06 s07 s08 s09 s10 rest wall msper)
  \\TIMECOORDS: (thousands, wall seconds) pairs; \\SCALE{n} / \\SCALEF{n}: overall score of each prefix"""
import json, re, sys
import os

def persian_number(t):
    """A number for Persian prose: Persian digits and separators in an LTR run (\\fanum, styles/custom.tex), since
    xepersian draws an unboxed ۱۲٫۵ as ۵٫۱۲ (the parts around a separator are reordered)."""
    t = t.replace('\\,', '\u066c').replace('.', '\u066b')
    if '\u066b' not in t and '\u066c' not in t:
        return t
    return r'\fanum{' + t.translate(str.maketrans('0123456789', '\u06f0\u06f1\u06f2\u06f3\u06f4\u06f5\u06f6\u06f7\u06f8\u06f9')) + '}'
ROOT = '/mnt/d/tez/practical/protocol_re/dol/' + os.environ.get('THESIS_FINAL', 'thesis-final-zs')
out = sys.argv[1]
L = [r'% generated by dol/thesis-numbers/gen_final.py from dol/thesis-final-zs -- do not edit by hand',
     r'\newcommand{\SUP}[2]{\csname SUP:#1:#2\endcsname}', r'\newcommand{\SUPF}[2]{\csname SUPF:#1:#2\endcsname}',
     r'\newcommand{\TIME}[2]{\csname TIME:#1:#2\endcsname}', r'\newcommand{\SCALE}[1]{\csname SCALE:#1\endcsname}',
     r'\newcommand{\SCALEF}[1]{\csname SCALEF:#1\endcsname}']
def d(name, v):
    L.append(rf'\expandafter\def\csname {name}\endcsname{{{v}}}')
for c in ('modbus-single', 'modbus-small', 'sajjad', 'goose'):
    data = f'{ROOT}/supplementary/{c}/data'
    r = json.load(open(f'{data}/15_evaluation_result.json')); m = r['metrics']
    vals = dict(overall=r['summary']['overall_score'], families=len(json.load(open(f'{data}/05_families.json'))),
                messages=sum(1 for _ in open(f'{data}/01_messages.jsonl')))
    for k, key in (('mt', 'message_type_matching'), ('bnd', 'field_boundary'), ('sem', 'field_semantics'), ('rel', 'relations')):
        vals[k] = m[key]['f1_score'] if m[key].get('applicable', True) else None
    for k, v in vals.items():
        s = '--' if v is None else (f'{v:.3f}' if isinstance(v, float) else f'{v:,}'.replace(',', '\\,'))
        d(f'SUP:{c}:{k}', s); d(f'SUPF:{c}:{k}', persian_number(s))
GROUPS = {'s04': ['04_discover_families'], 's04b': ['04b_fewshot_boundaries'], 's05': ['05_infer_framing'], 's06': ['06_extract_features'],
          's07': ['07_infer_boundaries', '07c_apply_fewshot_edges'], 's08': ['08_pair_requests_responses'], 's09': ['09_infer_keywords'], 's10': ['10_infer_relations']}
walls = {l.split()[0]: float(l.split()[2]) for l in open(f'{ROOT}/scaling-single/wall.txt') if 'total_wall' in l}
coords = []
for n in (10000, 25000, 50000, 100000, 200000):
    key = f'n{n}'
    t = {}
    for line in open(f'{ROOT}/scaling-single/{key}/log/pipeline.log'):
        mm = re.search(r'Completed stage: (\d\d[a-z]?_[a-z_]+) in ([\d.]+)s', line)
        if mm: t[mm.group(1)] = float(mm.group(2))
    used = 0.0
    for g, stages in GROUPS.items():
        v = sum(t.get(s, 0.0) for s in stages); used += v; d(f'TIME:{key}:{g}', f'{v:.1f}')
    d(f'TIME:{key}:rest', f'{sum(t.values()) - used:.1f}')
    d(f'TIME:{key}:wall', f'{walls[key]:.1f}'); d(f'TIME:{key}:msper', f'{1000 * walls[key] / n:.2f}')
    coords.append(f'({n // 1000},{walls[key]:.1f})')
    sc = json.load(open(f'{ROOT}/scaling-single/{key}/data/15_evaluation_result.json'))['summary']['overall_score']
    d(f'SCALE:{key}', f'{sc:.3f}'); d(f'SCALEF:{key}', persian_number(f'{sc:.3f}'))
L.append(r'\newcommand{\TIMECOORDS}{' + ''.join(coords) + '}')
# per-protocol pipeline time on the 14-protocol benchmark (sum of top-level stage times, default zero-shot runs) and the zero-shot
# overhead (stage 04b) on Modbus
def stage_times(path):
    t = {}
    for line in open(path):
        mm = re.search(r'Completed stage: (\d\d[a-z]?_[a-z_]+) in ([\d.]+)s', line)
        if mm: t[mm.group(1)] = float(mm.group(2))
    return t
BENCH = '/mnt/d/tez/practical/protocol_re/dol/' + os.environ.get('THESIS_RUNS', 'final-v4')
tot = {p: sum(stage_times(f'{BENCH}/zs/{p}/log/pipeline.log').values()) for p in
       ['bacnet', 'cip', 'dnp3', 'enip', 'ethercat', 'goose', 'hart_ip', 'iec104', 'mms', 'modbus', 'opcua', 'powerlink', 's7comm', 'zigbee']}
lo, hi = min(tot, key=tot.get), max(tot, key=tot.get)
d('BENCH:min', f'{tot[lo]:.0f}'); d('BENCH:minp', lo); d('BENCH:max', f'{tot[hi]:.0f}'); d('BENCH:maxp', hi)
zs = stage_times(f'{BENCH}/zs/modbus/log/pipeline.log').get('04b_fewshot_boundaries', 0.0)
d('BENCH:zsmodbus', f'{zs:.0f}')
L.append(r'\newcommand{\BENCH}[1]{\csname BENCH:#1\endcsname}')
print('benchmark times', round(tot[lo], 1), lo, round(tot[hi], 1), hi, 'zs 04b modbus', zs)
open(out, 'w').write('\n'.join(L) + '\n')
print('wrote', out)
