"""Write the thesis' main-result numbers as LaTeX macros from truth-eval run directories.
usage: gen_main.py <runs-root under dol/> <out.tex>
  \\R{config}{protocol}{metric}   number for tables / Latin text  (0.458)
  \\RF{config}{protocol}{metric}  same number for Persian text (\\fanum{۰٫۴۵۸}: Persian digits in an LTR run)
configs: rules zs zsshared fs10 fs20 fs50 rulesS zsS fs50S (S = 500-message samples); protocol 'macro' for averages;
metrics: overall bnd sem mt families frm frmdeep (framing accuracy / share with a deeper body start: share of messages whose family's predicted body start equals
the truth file's header length; reported beside the scores, not part of them); for protocol 'macro' also delta cilo cihi up down (vs rules, paired bootstrap).
Also \\MainTableRows, \\MainMacroRows and \\Coords{config} (pgfplots coordinates of overall per protocol)."""
import importlib.util, json, os, random, sys

def persian_number(t):
    """A number for Persian prose: Persian digits and separators in an LTR run (\\fanum, styles/custom.tex), since
    xepersian draws an unboxed ۱۲٫۵ as ۵٫۱۲ (the parts around a separator are reordered)."""
    t = t.replace('\\,', '\u066c').replace('.', '\u066b')
    if '\u066b' not in t and '\u066c' not in t:
        return t
    return r'\fanum{' + t.translate(str.maketrans('0123456789', '\u06f0\u06f1\u06f2\u06f3\u06f4\u06f5\u06f6\u06f7\u06f8\u06f9')) + '}'
ROOT = '/mnt/d/tez/practical/protocol_re'
runs, out = sys.argv[1], sys.argv[2]
P = ['bacnet', 'cip', 'dnp3', 'enip', 'ethercat', 'goose', 'hart_ip', 'iec104', 'mms', 'modbus', 'opcua', 'powerlink', 's7comm', 'zigbee']
LABEL = {'bacnet': 'BACnet', 'cip': 'CIP', 'dnp3': 'DNP3', 'enip': 'EtherNet/IP', 'ethercat': 'EtherCAT', 'goose': 'GOOSE',
         'hart_ip': 'HART-IP', 'iec104': 'IEC 104', 'mms': 'MMS', 'modbus': 'Modbus', 'opcua': 'OPC UA', 'powerlink': 'POWERLINK',
         's7comm': 'S7comm', 'zigbee': 'ZigBee'}
SYM = {'bacnet': 'BACnet', 'cip': 'CIP', 'dnp3': 'DNP3', 'enip': 'ENIP', 'ethercat': 'EtherCAT', 'goose': 'GOOSE', 'hart_ip': 'HART-IP',
       'iec104': 'IEC104', 'mms': 'MMS', 'modbus': 'Modbus', 'opcua': 'OPCUA', 'powerlink': 'PLink', 's7comm': 'S7comm', 'zigbee': 'ZigBee'}
CONF = {'rules': 'full', 'zs': 'zs', 'zsshared': 'zs-shared', 'fs10': 'fs10', 'fs20': 'fs20', 'fs50': 'fs50',
        'rulesS': 'sample', 'zsS': 'sample-runs/zs', 'fs50S': 'sample-runs/fs50'}
_spec = importlib.util.spec_from_file_location('ev', f'{ROOT}/scripts/17_evaluate_protocol_spec.py')
ev = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(ev)
def framing_accuracy(d, p):
    truth = json.load(open(f'{ROOT}/truth_files/{p}.json'))
    hl = ev._truth_header_length((truth.get('ground_truth_protocol') or truth.get('predicted_protocol'))['message_types'])
    fams = json.load(open(f'{d}/14_evaluation_model_data.json'))['predicted_protocol']['families']
    n = max(1, sum(int(f.get('message_count') or 0) for f in fams))
    share = lambda ok: sum(int(f.get('message_count') or 0) for f in fams if ok(ev._family_body_offset(f))) / n
    return share(lambda b: b == hl), share(lambda b: b > hl)
def load(c, p):
    d = f'{ROOT}/dol/{runs}/{CONF[c]}/{p}/data'
    r = json.load(open(f'{d}/15_evaluation_result.json')); m = r['metrics']
    fams = len(json.load(open(f'{d}/05_families.json')))
    return dict(overall=r['summary']['overall_score'], bnd=m['field_boundary']['f1_score'], sem=m['field_semantics']['f1_score'],
                mt=m['message_type_matching']['f1_score'], families=fams, **dict(zip(('frm', 'frmdeep'), framing_accuracy(d, p))))
V = {c: {p: load(c, p) for p in P} for c in CONF}
lines = ['% generated by dol/thesis-numbers/gen_main.py from dol/' + runs + ' -- do not edit by hand',
         r'\newcommand{\R}[3]{\csname R:#1:#2:#3\endcsname}', r'\newcommand{\RF}[3]{\csname RF:#1:#2:#3\endcsname}',
         r'\newcommand{\Coords}[1]{\csname C:#1\endcsname}']
def put(c, p, k, v, digits=3):
    s = (f'{v:+.{digits}f}' if k in ('delta', 'cilo', 'cihi') else f'{v:.{digits}f}') if isinstance(v, float) else str(v)
    lines.append(rf'\expandafter\def\csname R:{c}:{p}:{k}\endcsname{{{s}}}')
    lines.append(rf'\expandafter\def\csname RF:{c}:{p}:{k}\endcsname{{{persian_number(s)}}}')
for c in CONF:
    for p in P:
        for k, v in V[c][p].items():
            put(c, p, k, v)
    for k in ('overall', 'bnd', 'sem', 'mt', 'frm', 'frmdeep'):
        put(c, 'macro', k, sum(V[c][p][k] for p in P) / len(P))
    base = 'rulesS' if c.endswith('S') else 'rules'
    if c != base:
        d = [V[c][p]['overall'] - V[base][p]['overall'] for p in P]
        rng = random.Random(0); b = sorted(sum(rng.choice(d) for _ in d) / len(d) for _ in range(10000))
        put(c, 'macro', 'delta', sum(d) / len(d)); put(c, 'macro', 'cilo', b[250]); put(c, 'macro', 'cihi', b[9750])
        put(c, 'macro', 'up', sum(x > 0.005 for x in d)); put(c, 'macro', 'down', sum(x < -0.005 for x in d))
    lines.append(rf'\expandafter\def\csname C:{c}\endcsname{{' + ''.join(f'({SYM[p]},{V[c][p]["overall"]:.3f})' for p in P) + '}')
main = ['rules', 'zs', 'zsshared', 'fs10', 'fs20', 'fs50']
lines.append(r'\newcommand{\MainTableRows}{%')
for p in P:
    best = max(V[c][p]['overall'] for c in main)
    cells = [(rf'\textbf{{{V[c][p]["overall"]:.3f}}}' if abs(V[c][p]['overall'] - best) < 5e-4 else f'{V[c][p]["overall"]:.3f}') for c in main]
    lines.append(f'{LABEL[p]} & ' + ' & '.join(cells) + r' \\')
lines.append('}')
lines.append(r'\newcommand{\MainMacroRows}{%')
for k, name in (('overall', 'Macro overall'), ('bnd', 'Macro boundary F1'), ('sem', 'Macro semantics F1'), ('mt', 'Macro message-type F1'), ('frm', 'Framing accuracy (messages)')):
    lines.append(f'{name} & ' + ' & '.join(rf'\R{{{c}}}{{macro}}{{{k}}}' for c in main) + r' \\')
lines.append(r'$\Delta$ overall vs.\ rules & -- & ' + ' & '.join(rf'{{\R{{{c}}}{{macro}}{{delta}}}}' for c in main[1:]) + r' \\')
lines.append(r'95\% CI & -- & ' + ' & '.join(rf'[\R{{{c}}}{{macro}}{{cilo}}, \R{{{c}}}{{macro}}{{cihi}}]' for c in main[1:]) + r' \\')
lines.append(r'Up / down & -- & ' + ' & '.join(rf'\R{{{c}}}{{macro}}{{up}} / \R{{{c}}}{{macro}}{{down}}' for c in main[1:]) + r' \\')
lines.append('}')
# Modbus slices
for n in ('n10000', 'n50000'):
    v = json.load(open(f'{ROOT}/dol/{runs}/scaling/{n}/data/15_evaluation_result.json'))['summary']['overall_score']
    put('slice', n, 'overall', v)
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out, len(lines), 'lines')
