"""Macros for the held-out protocols (dol/heldout/scores.json): \\HO{protocol}{system}{key} / \\HOF (Persian decimal),
systems nemesys netzob netplier ours-rules ours-zs ours-fs50 (+ -s for sample-only runs), keys p r f1 v ari;
\\HeldoutRows: per-message boundary F1 table rows. usage: gen_heldout.py <out.tex>"""
import json, sys

def persian_number(t):
    """A number for Persian prose: Persian digits and separators in an LTR run (\\fanum, styles/custom.tex), since
    xepersian draws an unboxed ۱۲٫۵ as ۵٫۱۲ (the parts around a separator are reordered)."""
    t = t.replace('\\,', '\u066c').replace('.', '\u066b')
    if '\u066b' not in t and '\u066c' not in t:
        return t
    return r'\fanum{' + t.translate(str.maketrans('0123456789', '\u06f0\u06f1\u06f2\u06f3\u06f4\u06f5\u06f6\u06f7\u06f8\u06f9')) + '}'
S = json.load(open('/mnt/d/tez/practical/protocol_re/dol/heldout/scores.json'))
L = ['% generated by dol/thesis-numbers/gen_heldout.py from dol/heldout -- do not edit by hand',
     r'\newcommand{\HO}[3]{\csname HO:#1:#2:#3\endcsname}', r'\newcommand{\HOF}[3]{\csname HOF:#1:#2:#3\endcsname}']
for p, rows in S.items():
    for n, row in rows.items():
        for k, v in row.items():
            t = f'{v:.3f}' if isinstance(v, float) else str(v)
            L.append(rf'\expandafter\def\csname HO:{p}:{n}:{k}\endcsname{{{t}}}')
            L.append(rf'\expandafter\def\csname HOF:{p}:{n}:{k}\endcsname{{{persian_number(t)}}}')
NAMES = [('nemesys', 'NEMESYS'), ('netzob', 'Netzob'), ('netplier', 'NetPlier'), ('ours-zs', 'Ours: zero-shot (default)'),
         ('ours-fs50', 'Ours: few-shot 50'), ('ours-rules', 'Ours: rules (reference)')]
for macro, pair in (('HeldoutRows', ('synphasor', 'ams')), ('HeldoutRowsB', ('doip', 'cnip'))):
  if not all(p in S for p in pair):
    continue
  L.append(rf'\newcommand{{\{macro}}}{{%')
  for n, label in NAMES + [('every-byte', 'Every byte (trivial)'), ('sup-copy-offsets', 'Copy nearest labelled (offsets)'),
                           ('sup-copy-align', 'Copy nearest labelled (alignment)')]:
    cells = []
    for p in pair:
        best = max(S[p][m]['f1'] for m, _ in NAMES)
        for k in ('p', 'r', 'f1'):
            v = f"{S[p][n][k]:.3f}"
            cells.append(rf'\textbf{{{v}}}' if k == 'f1' and n in dict(NAMES) and abs(S[p][n]['f1'] - best) < 5e-4 else v)
        cells.append(f"{S[p][n]['v']:.2f}" if 'v' in S[p][n] else '--')
    if n == 'every-byte':
        L.append(r'\midrule')
    if n == 'sup-copy-offsets':
        L.append(r'\midrule')
    L.append(f'{label} & ' + ' & '.join(cells) + r' \\')
  L.append('}')
open(sys.argv[1], 'w').write('\n'.join(L) + '\n')
print('wrote', sys.argv[1])
