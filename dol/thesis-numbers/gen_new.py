"""Thesis macros for the review-pass experiments (\\NX{group}{key} Latin, \\NXF{group}{key} Persian):
  copy   few-shot 50 vs the copy baselines fed through the pipeline (dol/fewshot-vs-copy)
  ho     held-out protocols scored against their truth files (dol/heldout-truth; truth_files/heldout)
  seed   default configuration with boundary-model training seeds 0-3 (seed 0 = dol/final-v4/zs; dol/boundary-seeds)
  lopo   leave-one-protocol-out encoders (dol/lopo-encoder)
Paired comparisons over protocols: mean difference, paired bootstrap 95% CI, exact sign-flip permutation p.
usage: gen_new.py <out.tex>   (groups whose runs are incomplete are skipped and reported)"""
import json, os, random, sys
ROOT = '/mnt/d/tez/practical/protocol_re'
P = ['bacnet', 'cip', 'dnp3', 'enip', 'ethercat', 'goose', 'hart_ip', 'iec104', 'mms', 'modbus', 'opcua', 'powerlink', 's7comm', 'zigbee']
H = ['synphasor', 'ams', 'doip', 'cnip']
HLABEL = {'synphasor': 'IEEE C37.118', 'ams': 'ADS/AMS', 'doip': 'DoIP', 'cnip': 'CN/IP'}

def fa(t):
    t = t.replace('.', '٫')
    return r'\fanum{' + t.translate(str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹')) + '}' if '٫' in t else t.translate(str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹'))
L = ['% generated by dol/thesis-numbers/gen_new.py -- do not edit by hand',
     r'\newcommand{\NX}[2]{\csname NX:#1:#2\endcsname}', r'\newcommand{\NXF}[2]{\csname NXF:#1:#2\endcsname}']
def put(g, k, v, signed=False, digits=3):
    t = (f'{v:+.{digits}f}' if signed else f'{v:.{digits}f}') if isinstance(v, float) else str(v)
    L.append(rf'\expandafter\def\csname NX:{g}:{k}\endcsname{{{t}}}'); L.append(rf'\expandafter\def\csname NXF:{g}:{k}\endcsname{{{fa(t)}}}')

def result(run):
    path = f'{run}/data/15_evaluation_result.json'
    if not os.path.exists(path):
        return None
    r = json.load(open(path)); m = r['metrics']
    return dict(overall=r['summary']['overall_score'], bnd=m['field_boundary']['f1_score'], sem=m['field_semantics']['f1_score'],
                mt=m['message_type_matching']['f1_score'], rel=m['relations']['f1_score'],
                families=len(json.load(open(f'{run}/data/05_families.json'))))
def table(root, protos):
    v = {p: result(f'{root}/{p}') for p in protos}
    return None if any(x is None for x in v.values()) else v
def sign_flip(d):
    n, obs = len(d), abs(sum(d))
    return sum(1 for m in range(1 << n) if abs(sum(x if m >> i & 1 else -x for i, x in enumerate(d))) >= obs - 1e-12) / (1 << n)
def compare(g, name, a, b, protos, key='overall'):
    d = [a[p][key] - b[p][key] for p in protos]
    rng = random.Random(0); bs = sorted(sum(rng.choice(d) for _ in d) / len(d) for _ in range(10000))
    put(g, f'{name}:d', sum(d) / len(d), True); put(g, f'{name}:lo', bs[250], True); put(g, f'{name}:hi', bs[9750], True)
    put(g, f'{name}:p', sign_flip(d)); put(g, f'{name}:up', sum(x > .005 for x in d)); put(g, f'{name}:down', sum(x < -.005 for x in d))
    print(g, name, round(sum(d) / len(d), 3), f'[{bs[250]:+.3f}, {bs[9750]:+.3f}]', 'p', round(sign_flip(d), 4))
def macro(g, cfg, v, protos):
    for k in ('overall', 'bnd', 'sem', 'mt', 'rel'):
        put(g, f'{cfg}:{k}', sum(v[p][k] for p in protos) / len(protos))

FV4 = f'{ROOT}/dol/final-v4'
base = {c: table(f'{FV4}/{d}', P) for c, d in (('rules', 'full'), ('zs', 'zs'), ('fs50', 'fs50'))}
# copy
cp = {c: table(f'{ROOT}/dol/fewshot-vs-copy/runs/copy-{c}', P) for c in ('offsets', 'align')}
if all(cp.values()):
    for c, v in (('fs50', base['fs50']), ('offsets', cp['offsets']), ('align', cp['align'])):
        macro('copy', c, v, P)
    for c in ('offsets', 'align'):
        for k in ('overall', 'bnd', 'sem'):
            compare('copy', f'{c}:{k}', base['fs50'], cp[c], P, k)
else:
    print('copy: incomplete')
# held-out with truth files
ho = {c: table(f'{ROOT}/dol/heldout-truth/runs/{c}', H) for c in ('rules', 'zs', 'fs50', 'copy')}
if all(ho.values()):
    for c, v in ho.items():
        macro('ho', c, v, H)
        for p in H:
            for k in ('overall', 'bnd', 'sem', 'mt'):
                put('ho', f'{c}:{p}:{k}', v[p][k])
            put('ho', f'{c}:{p}:families', v[p]['families'])
    for a, b in (('zs', 'rules'), ('fs50', 'rules'), ('fs50', 'zs'), ('fs50', 'copy')):
        d = [ho[a][p]['overall'] - ho[b][p]['overall'] for p in H]
        put('ho', f'{a}-{b}:d', sum(d) / 4, True); put('ho', f'{a}-{b}:up', sum(x > .005 for x in d)); put('ho', f'{a}-{b}:down', sum(x < -.005 for x in d))
    # benchmark macro of the same configurations, for the side-by-side
    for c in ('rules', 'zs', 'fs50'):
        put('ho', f'bench:{c}:overall', sum(base[c][p]['overall'] for p in P) / 14)
    rows = []
    for p in H:
        cells = [HLABEL[p]] + [f"{ho[c][p]['overall']:.3f}" for c in ('rules', 'zs', 'fs50', 'copy')] + [f"{ho['zs'][p]['bnd']:.3f}", f"{ho['fs50'][p]['bnd']:.3f}", str(ho['zs'][p]['families'])]
        rows.append(' & '.join(cells) + r' \\')
    rows.append('Mean (4) & ' + ' & '.join(f"{sum(ho[c][p]['overall'] for p in H) / 4:.3f}" for c in ('rules', 'zs', 'fs50', 'copy'))
                + f" & {sum(ho['zs'][p]['bnd'] for p in H) / 4:.3f} & {sum(ho['fs50'][p]['bnd'] for p in H) / 4:.3f} & -- \\\\")
    rows.append('Benchmark mean (14) & ' + ' & '.join(f"{sum(base[c][p]['overall'] for p in P) / 14:.3f}" for c in ('rules', 'zs', 'fs50'))
                + ' & -- & ' + f"{sum(base['zs'][p]['bnd'] for p in P) / 14:.3f} & {sum(base['fs50'][p]['bnd'] for p in P) / 14:.3f} & -- \\\\")
    L.append(r'\newcommand{\HeldoutTruthRows}{%'); L.extend(rows); L.append('}')
else:
    print('ho: incomplete', {c: v is not None for c, v in ho.items()})
# boundary-model seeds
sd = {s: table(f'{ROOT}/dol/boundary-seeds/runs/seed{s}', P) for s in (1, 2, 3)}
if all(sd.values()):
    runs = {0: base['zs'], **sd}
    ov = {s: sum(v[p]['overall'] for p in P) / 14 for s, v in runs.items()}
    put('seed', 'min', min(ov.values())); put('seed', 'max', max(ov.values()))
    put('seed', 'bndmin', min(sum(v[p]['bnd'] for p in P) / 14 for v in runs.values()))
    put('seed', 'bndmax', max(sum(v[p]['bnd'] for p in P) / 14 for v in runs.values()))
    ds, ps = [], []
    for s, v in runs.items():
        d = [v[p]['overall'] - base['rules'][p]['overall'] for p in P]
        ds.append(sum(d) / 14); ps.append(sign_flip(d))
    put('seed', 'dmin', min(ds), True); put('seed', 'dmax', max(ds), True); put('seed', 'pmax', max(ps))
    spread = [max(v[p]['overall'] for v in runs.values()) - min(v[p]['overall'] for v in runs.values()) for p in P]
    put('seed', 'spreadmax', max(spread)); put('seed', 'spreadproto', max(P, key=lambda p: spread[P.index(p)]))
    put('seed', 'spreadmean', sum(spread) / 14)
    print('seed', {s: round(x, 3) for s, x in ov.items()}, 'delta vs rules', [round(x, 3) for x in ds], 'p', [round(x, 4) for x in ps])
else:
    print('seed: incomplete')
# leave-one-protocol-out encoders
lo = {m: {p: result(f'{ROOT}/dol/lopo-encoder/runs/{m if m == "all" else "no-" + p}/{p}') for p in P} for m in ('lopo', 'all')}
lo = {m: (None if any(x is None for x in v.values()) else v) for m, v in lo.items()}
if all(lo.values()):
    for m, v in (('lopo', lo['lopo']), ('all', lo['all']), ('deployed', base['zs'])):
        macro('lopo', m, v, P)
    compare('lopo', 'lopo-all', lo['lopo'], lo['all'], P)
    compare('lopo', 'lopo-deployed', lo['lopo'], base['zs'], P)
    compare('lopo', 'lopo-rules', lo['lopo'], base['rules'], P)
    compare('lopo', 'mt', lo['lopo'], lo['all'], P, 'mt')
    struct = table(f'{ROOT}/dol/ablation-final/runs/structural-features', P)
    if struct:
        macro('lopo', 'struct', struct, P)
        compare('lopo', 'lopo-struct', lo['lopo'], struct, P)
    put('lopo', 'collapsed', sum(1 for p in P if (json.load(open(f'{ROOT}/dol/lopo-encoder/runs/no-{p}/{p}/data/02_family_assignments.json')).get('metadata') or {}).get('discriminator_refinement', {}).get('family_count_before') == 1))
    put('lopo', 'worst', min(P, key=lambda p: lo['lopo'][p]['overall'] - lo['all'][p]['overall']))
    put('lopo', 'worstd', min(lo['lopo'][p]['overall'] - lo['all'][p]['overall'] for p in P), True)
    for p in P:
        put('lopo', f'{p}:lopo', lo['lopo'][p]['overall']); put('lopo', f'{p}:all', lo['all'][p]['overall'])
else:
    print('lopo: incomplete')
# encoder clustering on the left-out protocol (dol/lopo-encoder/cluster_eval.py)
ce_path = f'{ROOT}/dol/lopo-encoder/cluster_eval.json'
LABEL = {'bacnet': 'BACnet', 'cip': 'CIP', 'dnp3': 'DNP3', 'enip': 'EtherNet/IP', 'ethercat': 'EtherCAT', 'goose': 'GOOSE', 'hart_ip': 'HART-IP',
         'iec104': 'IEC 104', 'mms': 'MMS', 'modbus': 'Modbus', 'opcua': 'OPC UA', 'powerlink': 'POWERLINK', 's7comm': 'S7comm', 'zigbee': 'ZigBee'}
if os.path.exists(ce_path):
    ce = json.load(open(ce_path))
    if all(f'{p}:{m}' in ce for p in P for m in ('lopo', 'all')):
        multi = [p for p in P if ce[f'{p}:all'].get('trusted_family_count', 0) >= 2]
        put('lopo', 'multi', len(multi))
        for m in ('lopo', 'all'):
            for k, n in (('weighted_cluster_purity', 'pur'), ('v_measure', 'v'), ('adjusted_rand_index', 'ari')):
                put('lopo', f'ce:{m}:{n}', sum(ce[f'{p}:{m}'][k] for p in multi) / len(multi))
        d = [ce[f'{p}:lopo']['v_measure'] - ce[f'{p}:all']['v_measure'] for p in multi]
        put('lopo', 'ce:vdrop', sum(x < -0.1 for x in d)); put('lopo', 'ce:vp', sign_flip(d))
        if all(lo.values()):
            rows = []
            for p in multi:
                rows.append(f"{LABEL[p]} & {ce[f'{p}:all']['v_measure']:.3f} & {ce[f'{p}:lopo']['v_measure']:.3f} & "
                            f"{lo['all'][p]['overall']:.3f} & {lo['lopo'][p]['overall']:.3f} & {base['zs'][p]['overall']:.3f} \\\\")
            L.append(r'\newcommand{\LopoRows}{%'); L.extend(rows); L.append('}')
            put('lopo', 'single', ', '.join(LABEL[p] for p in P if p not in multi))
        print('ce', {m: round(sum(ce[f'{p}:{m}']['v_measure'] for p in multi) / len(multi), 3) for m in ('lopo', 'all')}, 'p', round(sign_flip(d), 4))
open(sys.argv[1], 'w').write('\n'.join(L) + '\n')
print('wrote', sys.argv[1])
