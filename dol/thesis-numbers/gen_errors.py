"""Boundary error analysis of the final configurations (truth-file reference, the <= 500-message evaluation samples
of dol/baseline-comparison): where missed truth edges lie, by the constancy of the two neighbouring bytes within the
message's family, and (for variable|variable misses) by the widths of the two adjacent truth fields.
Protocol-weighted (each protocol 1/14).
usage: gen_errors.py <runs-root under dol/> <out.tex>"""
import json, os, sys
from collections import Counter, defaultdict
ROOT = '/mnt/d/tez/practical/protocol_re'
runs, out = sys.argv[1], sys.argv[2]
sys.path.insert(0, f'{ROOT}/src')
from protocol_re.inference.tlv import message_layout_edges

def persian_number(t):
    """A number for Persian prose: Persian digits and separators in an LTR run (\\fanum, styles/custom.tex), since
    xepersian draws an unboxed ۱۲٫۵ as ۵٫۱۲ (the parts around a separator are reordered)."""
    t = t.replace('\\,', '\u066c').replace('.', '\u066b')
    if '\u066b' not in t and '\u066c' not in t:
        return t
    return r'\fanum{' + t.translate(str.maketrans('0123456789', '\u06f0\u06f1\u06f2\u06f3\u06f4\u06f5\u06f6\u06f7\u06f8\u06f9')) + '}'
P = ['bacnet', 'cip', 'dnp3', 'enip', 'ethercat', 'goose', 'hart_ip', 'iec104', 'mms', 'modbus', 'opcua', 'powerlink', 's7comm', 'zigbee']
CONF = {'rules': 'full', 'zs': 'zs'}
def wcat(w): return '1' if w == 1 else ('2' if w == 2 else ('3-4' if w <= 4 else '5+'))
res = {}
for c, sub in CONF.items():
    neigh = defaultdict(float); widths = defaultdict(float); fp_inside = 0.0; rec = prec = 0.0
    for p in P:
        d = f'{ROOT}/dol/{runs}/{sub}/{p}/data'
        fams = json.load(open(f'{d}/05_families.json'))
        assign = {a['msg_id']: str(a['family_id']) for a in json.load(open(f'{d}/02_family_assignments.json'))['assignments']}
        msgs = {json.loads(l)['msg_id']: bytes.fromhex(json.loads(l)['payload_hex']) for l in open(f'{d}/01_messages.jsonl')}
        ids = set(json.load(open(f'{ROOT}/dol/baseline-comparison/samples/{p}.json')))
        truth = {a['msg_id']: a['boundaries'] for a in map(json.loads, open(f'{ROOT}/dol/accuracy-push/annotations-truthconv/{p}.jsonl')) if a['msg_id'] in ids}
        edges = {}
        for fid, det in fams.items():
            v = set()
            for f in det.get('field_hypotheses', []) or []:
                v.update((int(f.get('start', 0) or 0), int(f.get('start', 0) or 0) + int(f.get('length', 0) or 0)))
            edges[fid] = sorted(v)
        members = defaultdict(list)
        for mid, fid in assign.items():
            members[fid].append(msgs[mid])
        const_cache = {}
        def const(fid, o):
            k = (fid, o)
            if k not in const_cache:
                vals = Counter(m[o] for m in members[fid] if len(m) > o)
                n = sum(vals.values())
                const_cache[k] = n > 0 and vals.most_common(1)[0][1] / n >= 0.95
            return const_cache[k]
        nc = Counter(); wc = Counter(); fn = fp = fpi = tp = 0
        for mid, t in truth.items():
            if mid not in msgs: continue
            b = msgs[mid]; L = len(b); fid = assign.get(mid)
            e = edges.get(fid, [])
            lay = fams.get(fid, {}).get('message_layout') if fid else None
            if lay: e = message_layout_edges(b, e, lay)
            pe = {x for x in e if 0 < x < L}; te = sorted({x for x in t if 0 < x < L})
            tc = [0] + te + [L]
            tp += len(pe & set(te))
            for x in set(te) - pe:
                fn += 1
                if fid is None or fid == 'noise':
                    nc['unassigned'] += 1; continue
                l, r = const(fid, x - 1), const(fid, x)
                cat = 'cc' if l and r else ('vv' if not l and not r else 'cv')
                nc[cat] += 1
                if cat == 'vv':
                    i = tc.index(x); wc[wcat(x - tc[i - 1]) + '|' + wcat(tc[i + 1] - x)] += 1
            for x in pe - set(te):
                fp += 1
                a = max(q for q in tc if q < x); z = min(q for q in tc if q > x)
                fpi += (z - a) >= 2
        nfn = max(1, fn)
        for k, v in nc.items(): neigh[k] += v / nfn / len(P)
        for k, v in wc.items(): widths[k] += v / nfn / len(P)
        fp_inside += (fpi / max(1, fp)) / len(P)
        rec += tp / max(1, tp + fn) / len(P); prec += tp / max(1, tp + fp) / len(P)
    res[c] = dict(neigh=neigh, widths=widths, fp_inside=fp_inside, rec=rec, prec=prec)
lines = ['% generated by dol/thesis-numbers/gen_errors.py from dol/' + runs + ' -- do not edit by hand',
         r'\newcommand{\E}[3]{\csname E:#1:#2:#3\endcsname}', r'\newcommand{\EF}[3]{\csname EF:#1:#2:#3\endcsname}']
def put(c, g, k, v, pct=True):
    s = f'{100 * v:.0f}' if pct else f'{v:.2f}'
    lines.append(rf'\expandafter\def\csname E:{c}:{g}:{k}\endcsname{{{s}}}')
    lines.append(rf'\expandafter\def\csname EF:{c}:{g}:{k}\endcsname{{{persian_number(s)}}}')
WK = ['1|1', '2|2', '3-4|3-4', '1|2', '2|1', '3-4|1', '1|3-4', '5+|5+']
for c, r in res.items():
    for k in ('vv', 'cv', 'cc', 'unassigned'):
        put(c, 'n', k, r['neigh'].get(k, 0.0))
    for k in WK:
        put(c, 'w', k, r['widths'].get(k, 0.0))
    put(c, 'x', 'rec', r['rec'], False); put(c, 'x', 'prec', r['prec'], False)
    lines.append(rf'\expandafter\def\csname EC:{c}:n\endcsname{{' + ''.join(f'({100 * r["neigh"].get(k, 0):.0f},{k})' for k in ('vv', 'cv', 'cc', 'unassigned')) + '}')
    lines.append(rf'\expandafter\def\csname EC:{c}:w\endcsname{{' + ''.join(f'({100 * r["widths"].get(k, 0):.0f},{k})' for k in WK) + '}')
lines.append(r'\newcommand{\EC}[2]{\csname EC:#1:#2\endcsname}')
open(out, 'w').write('\n'.join(lines) + '\n')
for c, r in res.items():
    print(c, {k: round(v, 3) for k, v in r['neigh'].items()}, 'fp_inside', round(r['fp_inside'], 3), 'R', round(r['rec'], 3), 'P', round(r['prec'], 3))
    print('   widths', sorted(((round(v, 3), k) for k, v in r['widths'].items()), reverse=True)[:8])
