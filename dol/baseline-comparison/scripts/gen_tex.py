"""Write the LaTeX tables/figure data for the thesis comparison section from scores.json and the tool metadata."""
import json, os, random, sys
from common import HERE, PROTOCOLS

def persian_number(t):
    """A number for Persian prose: Persian digits and separators in an LTR run (\\fanum, styles/custom.tex), since
    xepersian draws an unboxed ۱۲٫۵ as ۵٫۱۲ (the parts around a separator are reordered)."""
    t = t.replace('\\,', '\u066c').replace('.', '\u066b')
    if '\u066b' not in t and '\u066c' not in t:
        return t
    return r'\fanum{' + t.translate(str.maketrans('0123456789', '\u06f0\u06f1\u06f2\u06f3\u06f4\u06f5\u06f6\u06f7\u06f8\u06f9')) + '}'
OUT = sys.argv[1]
r = json.load(open(os.path.join(HERE, 'scores.json')))
TOOLS = ['nemesys', 'netzob', 'netplier']
OURS = ['ours-det', 'ours-zs', 'ours-fs50']
NAMES = TOOLS + OURS
LABEL_TOOL = {'nemesys': 'NEMESYS', 'netzob': 'Netzob', 'netplier': 'NetPlier'}
LABEL = {'bacnet': 'BACnet', 'cip': 'CIP', 'dnp3': 'DNP3', 'enip': 'EtherNet/IP', 'ethercat': 'EtherCAT', 'goose': 'GOOSE',
         'hart_ip': 'HART-IP', 'iec104': 'IEC 104', 'mms': 'MMS', 'modbus': 'Modbus', 'opcua': 'OPC UA',
         'powerlink': 'POWERLINK', 's7comm': 'S7comm', 'zigbee': 'ZigBee'}
def meta(t, p):
    path = os.path.join(HERE, 'preds', t, p + '.meta.json')
    return json.load(open(path)) if os.path.exists(path) else {}
def f1(p, n, ref): return r[p][n][ref]['f1'] if n in r[p] else 0.0
def has(p, n): return n in r[p]
def cell(p, n, ref, best):
    if not has(p, n):
        return 'DNF'
    v = f'{f1(p, n, ref):.3f}'
    return f'\\textbf{{{v}}}' if abs(f1(p, n, ref) - best) < 5e-4 else v
def ci(a, b, ref, B=10000):
    d = [f1(p, a, ref) - f1(p, b, ref) for p in PROTOCOLS]
    rng = random.Random(0); boots = sorted(sum(rng.choice(d) for _ in d) / len(d) for _ in range(B))
    return sum(d) / len(d), boots[int(0.025 * B)], boots[int(0.975 * B)], sum(x > 0 for x in d), sum(x < 0 for x in d)
def sign_flip_p(d):
    """Exact two-sided paired sign-flip permutation p-value of the mean difference over the protocols."""
    n, obs = len(d), abs(sum(d))
    return sum(1 for mask in range(1 << n) if abs(sum(x if mask >> i & 1 else -x for i, x in enumerate(d))) >= obs - 1e-12) / (1 << n)
common = [p for p in PROTOCOLS if all(has(p, n) for n in NAMES)]
lines = []
w = lines.append
# --- per-protocol F1 table rows (truth ref), macro rows for both refs
w('% generated by dol/baseline-comparison/scripts/gen_tex.py -- do not edit by hand')
w('\\newcommand{\\BaselineRowsTruth}{%')
for p in PROTOCOLS:
    best = max(f1(p, n, 'truth') for n in NAMES)
    w(f"{LABEL[p]} & " + ' & '.join(cell(p, n, 'truth', best) for n in NAMES) + ' \\\\')
w('}')
for ref, tag in (('truth', 'Truth'), ('parser', 'Parser')):
    w(f'\\newcommand{{\\BaselineMacro{tag}}}{{' + ' & '.join(f'{sum(f1(p, n, ref) for p in PROTOCOLS) / 14:.3f}' for n in NAMES) + '}')
    w(f'\\newcommand{{\\BaselineMacroCommon{tag}}}{{' + ' & '.join(f'{sum(f1(p, n, ref) for p in common) / len(common):.3f}' for n in NAMES) + '}')
    w(f'\\newcommand{{\\BaselineP{tag}}}{{' + ' & '.join(f"{sum(r[p][n][ref]['precision'] for p in PROTOCOLS if has(p, n)) / 14:.2f}" for n in NAMES) + '}')
    w(f'\\newcommand{{\\BaselineR{tag}}}{{' + ' & '.join(f"{sum(r[p][n][ref]['recall'] for p in PROTOCOLS if has(p, n)) / 14:.2f}" for n in NAMES) + '}')
    w(f'\\newcommand{{\\BaselinePlot{tag}}}{{' + ''.join(f'({i},{sum(f1(p, n, ref) for p in PROTOCOLS) / 14:.3f})' for i, n in enumerate(NAMES)) + '}')
w(f'\\newcommand{{\\BaselineCommonCount}}{{{len(common)}}}')
# --- paired bootstrap rows
w('\\newcommand{\\BaselineCIRows}{%')
for o in OURS:
    for k, t in enumerate(TOOLS):
        cells = []
        for ref in ('truth', 'parser'):
            m, lo, hi, up, down = ci(o, t, ref)
            cells += [f'{m:+.3f}', f'[{lo:+.3f}, {hi:+.3f}]', f'{up} / {down}']
        name = {'ours-det': 'Rules', 'ours-zs': 'Zero-shot', 'ours-fs50': 'Few-shot 50'}[o] if k == 0 else ''
        w(f"{name} & {LABEL_TOOL[t]} & " + ' & '.join(cells) + ' \\\\')
    if o != OURS[-1]:
        w('\\midrule')
w('}')
# --- clustering (protocols with >= 2 true message types), per tool on the protocols it covers and on the common set
multi = [p for p in PROTOCOLS if r[p]['ours-det'].get('clustering', {}).get('true_types', 0) >= 2]
cl_names = ['netzob', 'netplier', 'ours-det', 'ours-fs50']
both = [p for p in multi if all('clustering' in r[p].get(n, {}) for n in cl_names)]
w('\\newcommand{\\BaselineClusterRows}{%')
for n in cl_names:
    rows = [r[p][n]['clustering'] for p in multi if 'clustering' in r[p].get(n, {})]
    rows_b = [r[p][n]['clustering'] for p in both]
    avg = lambda rs, k: sum(x[k] for x in rs) / len(rs)
    name = {'netzob': 'Netzob', 'netplier': 'NetPlier', 'ours-det': 'Ours, rule-based / zero-shot', 'ours-fs50': 'Ours, few-shot 50'}[n]
    w(f"{name} & {len(rows)} & {avg(rows, 'clusters'):.1f} & {avg(rows, 'homogeneity'):.3f} & {avg(rows, 'completeness'):.3f} & "
      f"{avg(rows, 'v_measure'):.3f} & {avg(rows, 'ari'):.3f} & {avg(rows_b, 'v_measure'):.3f} & {avg(rows_b, 'ari'):.3f} \\\\")
w('}')
w(f'\\newcommand{{\\BaselineClusterCommon}}{{{len(both)}}}')
w(f'\\newcommand{{\\BaselineClusterMulti}}{{{len(multi)}}}')
# --- Netzob threshold sweep (protocols the sweep covered)
sweep = sorted({d for d in os.listdir(os.path.join(HERE, 'preds')) if d.startswith('netzob-eq')} | {'netzob'},
               key=lambda d: int(d[9:]) if d != 'netzob' else 50)
sp = [p for p in PROTOCOLS if all(has(p, d) for d in sweep)]
w('\\newcommand{\\NetzobSweepRows}{%')
for d in sweep:
    eq = 50 if d == 'netzob' else int(d[9:])
    cs = [r[p][d]['clustering'] for p in sp if p in multi and 'clustering' in r[p][d]]
    w(f"{eq}{' (default)' if d == 'netzob' else ''} & {sum(f1(p, d, 'truth') for p in sp) / len(sp):.3f} & {sum(f1(p, d, 'parser') for p in sp) / len(sp):.3f} & "
      f"{sum(c['clusters'] for c in cs) / len(cs):.1f} & {sum(c['v_measure'] for c in cs) / len(cs):.3f} & {sum(c['ari'] for c in cs) / len(cs):.3f} \\\\")
w('}')
w(f'\\newcommand{{\\NetzobSweepCount}}{{{len(sp)}}}')
w('\\newcommand{\\NetzobSweepOurs}{' + f"{sum(f1(p, 'ours-det', 'truth') for p in sp) / len(sp):.3f} & {sum(f1(p, 'ours-det', 'parser') for p in sp) / len(sp):.3f}" + '}')
# --- runtimes and failures
for t in TOOLS:
    secs = [meta(t, p).get('seconds', 0) for p in PROTOCOLS]
    w(f"\\newcommand{{\\Runtime{t.capitalize()}}}{{{persian_number(f'{sum(secs) / 60:.1f}')}}}")
# --- prose macros: \B{system}{ref}{key} (Latin) / \BF (Persian decimal); systems incl. sample-only ours-*-s
w(r'\newcommand{\B}[3]{\csname B:#1:#2:#3\endcsname}')
w(r'\newcommand{\BF}[3]{\csname BF:#1:#2:#3\endcsname}')
def put(n, ref, key, v, digits=3):
    t = f'{v:+.{digits}f}' if key in ('dnp', 'lo', 'hi', 'odelta', 'flddnp', 'fldlo', 'fldhi', 'dcopy', 'dcopylo', 'dcopyhi') else (f'{v:.{digits}f}' if isinstance(v, float) else str(v))
    w(rf'\expandafter\def\csname B:{n}:{ref}:{key}\endcsname{{{t}}}')
    w(rf'\expandafter\def\csname BF:{n}:{ref}:{key}\endcsname{{{persian_number(t.lstrip("+"))}}}')
# every-byte reference baseline (a boundary after every byte): macro P/R/F1, per-protocol F1, the protocols where it
# beats our zero-shot configuration (truth files), and the share of positions each method marks as an edge
for ref in ('truth', 'parser'):
    for key, k in (('f1', 'f1'), ('p', 'precision'), ('r', 'recall')):
        put('every-byte', ref, key, sum(r[p]['every-byte'][ref][k] for p in PROTOCOLS) / 14)
for p in PROTOCOLS:
    put('every-byte', p, 'f1', f1(p, 'every-byte', 'truth'))
beats = [p for p in PROTOCOLS if f1(p, 'every-byte', 'truth') > f1(p, 'ours-zs', 'truth')]
w(r'\newcommand{\EveryByteBeatsZSCount}{' + str(len(beats)) + '}')
w(r'\newcommand{\EveryByteBeatsZS}{' + '، '.join(r'\en{' + LABEL[p] + '}' for p in beats) + '}')
for n in TOOLS + OURS:
    d = [r[p][n]['truth']['density'] for p in PROTOCOLS if has(p, n)]
    put(n, 'density', 'mean', 100 * sum(d) / len(d), 0)
    put(n, 'density', 'min', 100 * min(d), 0); put(n, 'density', 'max', 100 * max(d), 0)
    put(n, 'density', 'n70', sum(x >= 0.7 for x in d))
ALL = NAMES + [n for n in ('ours-det-s', 'ours-zs-s', 'ours-fs50-s') if any(n in r[p] for p in PROTOCOLS)]
for n in ALL:
    for ref in ('truth', 'parser'):
        put(n, ref, 'f1', sum(f1(p, n, ref) for p in PROTOCOLS) / 14)
        put(n, ref, 'p', sum(r[p][n][ref]['precision'] for p in PROTOCOLS if has(p, n)) / 14, 2)
        put(n, ref, 'r', sum(r[p][n][ref]['recall'] for p in PROTOCOLS if has(p, n)) / 14, 2)
        if n.startswith('ours'):
            m, lo, hi, up, down = ci(n, 'netplier', ref)
            put(n, ref, 'dnp', m); put(n, ref, 'lo', lo); put(n, ref, 'hi', hi); put(n, ref, 'up', up); put(n, ref, 'down', down)
            put(n, ref, 'pnp', sign_flip_p([f1(p, n, ref) - f1(p, 'netplier', ref) for p in PROTOCOLS]))
            if has(PROTOCOLS[0], 'every-byte'):
                put(n, ref, 'peb', sign_flip_p([f1(p, n, ref) - f1(p, 'every-byte', ref) for p in PROTOCOLS]))
                put(n, ref, 'deb', sum(f1(p, n, ref) - f1(p, 'every-byte', ref) for p in PROTOCOLS) / 14)
            oracle = [max(f1(p, b, ref) for b in TOOLS) for p in PROTOCOLS]
            d = [f1(p, n, ref) - o for p, o in zip(PROTOCOLS, oracle)]
            put(n, ref, 'odelta', sum(d) / 14); put(n, ref, 'oup', sum(x > 0 for x in d)); put(n, ref, 'odown', sum(x < 0 for x in d))
    rows = [r[p][n]['clustering'] for p in multi if 'clustering' in r[p].get(n, {})]
    if rows:
        put(n, 'clu', 'v', sum(x['v_measure'] for x in rows) / len(rows)); put(n, 'clu', 'ari', sum(x['ari'] for x in rows) / len(rows))
for ref in ('truth', 'parser'):
    put('oracle', ref, 'f1', sum(max(f1(p, b, ref) for b in TOOLS) for p in PROTOCOLS) / 14)
for p in PROTOCOLS:
    for n in ALL:
        if has(p, n):
            put(n, p, 'f1', f1(p, n, 'truth'))
            if 'clustering' in r[p][n]:
                put(n, p, 'v', r[p][n]['clustering']['v_measure'])
# sample-only rows for the comparison table
SAMPLE = [n for n in ('ours-det-s', 'ours-zs-s', 'ours-fs50-s') if n in ALL]
# exact-field F1 (a reference field counts only if both its edges are predicted and none inside; predicted fields
# likewise), macro over 14 protocols, both references, every system; CIs of ours vs NetPlier
def fld(p, n, ref): return r[p][n][ref]['field_f1'] if n in r[p] else 0.0
def ci_k(a, b, ref, get, B=10000):
    d = [get(p, a, ref) - get(p, b, ref) for p in PROTOCOLS]
    rng = random.Random(0); boots = sorted(sum(rng.choice(d) for _ in d) / len(d) for _ in range(B))
    return sum(d) / len(d), boots[int(0.025 * B)], boots[int(0.975 * B)], sum(x > 0 for x in d), sum(x < 0 for x in d)
FIELD = ['every-byte'] + NAMES
w('\\newcommand{\\BaselineFieldTruth}{' + ' & '.join(f'{sum(fld(p, n, "truth") for p in PROTOCOLS) / 14:.3f}' for n in NAMES) + '}')
w('\\newcommand{\\BaselineFieldParser}{' + ' & '.join(f'{sum(fld(p, n, "parser") for p in PROTOCOLS) / 14:.3f}' for n in NAMES) + '}')
for n in FIELD + ['sup-copy-offsets', 'sup-copy-align', 'ours-fs50-msg', 'ours-zs-msg']:
    for ref in ('truth', 'parser'):
        if any(n in r[p] for p in PROTOCOLS):
            put(n, ref, 'fld', sum(fld(p, n, ref) for p in PROTOCOLS) / 14)
for n in ('ours-det', 'ours-zs', 'ours-fs50'):
    for ref in ('truth', 'parser'):
        m, lo, hi, up, down = ci_k(n, 'netplier', ref, fld)
        put(n, ref, 'fldpnp', sign_flip_p([fld(p, n, ref) - fld(p, 'netplier', ref) for p in PROTOCOLS]))
        put(n, ref, 'flddnp', m); put(n, ref, 'fldlo', lo); put(n, ref, 'fldhi', hi); put(n, ref, 'fldup', up); put(n, ref, 'flddown', down)
# supervised reference baselines (same 50 labels as few-shot, labelled messages not scored): few-shot vs copying
SUP = ['sup-copy-offsets', 'sup-copy-align', 'ours-fs50', 'ours-fs50-msg']
SUPL = {'sup-copy-offsets': 'Copy nearest labelled message (offsets)', 'sup-copy-align': 'Copy nearest labelled message (alignment)',
        'ours-fs50': 'Ours, few-shot 50 (family field lists)', 'ours-fs50-msg': 'Ours, few-shot 50 (per-message edges)'}
w(r'\newcommand{\SupRows}{%')
for n in SUP:
    cells = []
    for ref in ('truth', 'parser'):
        cells += [f"{sum(f1(p, n, ref) for p in PROTOCOLS) / 14:.3f}", f"{sum(fld(p, n, ref) for p in PROTOCOLS) / 14:.3f}"]
    w(SUPL[n] + ' & ' + ' & '.join(cells) + r' \\')
w('}')
for n in SUP:
    for ref in ('truth', 'parser'):
        put(n, ref, 'f1', sum(f1(p, n, ref) for p in PROTOCOLS) / 14)
for a in ('ours-fs50', 'ours-fs50-msg'):
    for ref in ('truth', 'parser'):
        m, lo, hi, up, down = ci_k(a, 'sup-copy-offsets', ref, f1)
        put(a, ref, 'dcopy', m); put(a, ref, 'dcopylo', lo); put(a, ref, 'dcopyhi', hi); put(a, ref, 'dcopyup', up); put(a, ref, 'dcopydown', down)
w(r'\newcommand{\BaselineSampleRows}{%')
for n in SAMPLE:
    cells = []
    for ref in ('truth', 'parser'):
        m, lo, hi, up, down = ci(n, 'netplier', ref)
        cells += [f"{sum(f1(p, n, ref) for p in PROTOCOLS) / 14:.3f}", f'{m:+.3f} [{lo:+.3f}, {hi:+.3f}]', f'{up} / {down}']
    w({'ours-det-s': 'Rules', 'ours-zs-s': 'Zero-shot', 'ours-fs50-s': 'Few-shot 50'}[n] + ' & ' + ' & '.join(cells) + r' \\')
w('}')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('common protocols:', common, '| cluster both:', both, '| sweep protocols:', sp)
for t in TOOLS:
    print(t, {p: meta(t, p).get('status', 'ok') for p in PROTOCOLS if meta(t, p).get('status', 'ok') != 'ok'})
